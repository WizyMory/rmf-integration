#!/usr/bin/env python3
"""Build reproducible products using installed RMF tools; preserve inputs."""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import xml.etree.ElementTree as ET
import yaml
from generate_nav2_map import generate
from map_geometry import graph_spawns
from validate_map_alignment import validate


def run(package):
    package = Path(package).resolve()
    source = package / 'maps/brin_0.building.yaml'
    simulation_models_source = package / 'maps/banyak_simpangan.building.yaml'
    original = yaml.safe_load(source.read_text())
    simulation_models = yaml.safe_load(simulation_models_source.read_text())
    model_names = [model['model_name']
                   for level in simulation_models['levels'].values()
                   for model in level.get('models', [])]
    model_assets = sorted({name.rsplit('/', 1)[-1] for name in model_names})
    for asset in model_assets:
        if not asset or Path(asset).name != asset:
            raise ValueError(f'Invalid simulation model asset name: {asset}')
        if not (package/'models'/asset/'model.sdf').is_file():
            raise FileNotFoundError(
                f'Simulation model [{asset}] must be vendored under models/{asset}')
    for folder in ('nav_graphs', 'worlds', 'models'):
        (package / folder).mkdir(exist_ok=True)
    subprocess.run(['ros2', 'run', 'rmf_building_map_tools', 'building_map_generator',
                    'nav', str(source), str(package/'nav_graphs')], check=True)
    indexes = {lane[2]['graph_idx'][1] for lane in original['levels']['L1']['lanes']}
    if len(indexes) != 1:
        raise ValueError(f'Select a fleet graph explicitly: {indexes}')
    graph = package / 'nav_graphs' / f'{indexes.pop()}.yaml'
    if not graph.is_file():
        raise FileNotFoundError('Inspect actual generator graph filenames')
    # Alignment validation uses a temporary reference-map metadata file. The
    # active brin_0.yaml is owned by the reviewed occupancy promotion gate and
    # must continue to point at brin_0_nav2.png.
    with tempfile.TemporaryDirectory(prefix='brin_reference_map_') as directory:
        reference_map = Path(directory) / 'brin_0.yaml'
        generate(source, reference_map)
        errors = validate(source, graph, reference_map)
    (package/'maps/spawns.yaml').write_text(yaml.safe_dump(graph_spawns(graph)))

    # Milestone 1 has permanently open doorways. Preserve all door and spawn
    # metadata in the authoritative input; only the world-generation copy is
    # stripped. Lanes with door events also have an explicitly derived graph.
    world_input = copy.deepcopy(original)
    if original['coordinate_system'] != simulation_models['coordinate_system']:
        raise ValueError('Simulation model source uses a different coordinate system')
    for level_name, level in world_input['levels'].items():
        model_level = simulation_models['levels'].get(level_name)
        if model_level is None:
            raise ValueError(f'Simulation model source is missing level {level_name}')
        if level.get('measurements') != model_level.get('measurements'):
            raise ValueError(f'Simulation model source scale differs on level {level_name}')
        base_image = package / 'maps' / level['drawing']['filename']
        model_image = package / 'maps' / model_level['drawing']['filename']
        if base_image.read_bytes() != model_image.read_bytes():
            raise ValueError(f'Simulation model source image differs on level {level_name}')
        # Keep the verified baseline building geometry, but take simulation-only
        # props from the user-edited traffic profile. These props are deliberately
        # absent from the Nav2 occupancy raster and the RMF schedule graph.
        level['models'] = copy.deepcopy(model_level.get('models', []))
        level['doors'] = []
        for vertex in level['vertices']:
            if len(vertex) > 4:
                vertex[4] = {k: v for k, v in vertex[4].items()
                             if not k.startswith('spawn_robot_')}
    with tempfile.TemporaryDirectory(prefix='brin_map_') as directory:
        temporary = Path(directory)/source.name
        temporary.write_text(yaml.safe_dump(world_input))
        # The installed generator appends materials: clear generated definitions
        # so regeneration does not duplicate their names.
        for material in (package/'models').glob('*/meshes/model.material'):
            material.write_text('')
        # Textures are generated by RMF; drawing is not used to redraw geometry.
        subprocess.run(['ros2', 'run', 'rmf_building_map_tools', 'building_map_generator',
                        'ignition', str(temporary), str(package/'worlds/brin.sdf'),
                        str(package/'models')], check=True)

    tree = ET.parse(package/'worlds/brin.sdf')
    world = tree.getroot().find('world')
    world.set('name', 'brin')
    # Stock RMF template contains demo robot plugins and online ground/sun
    # includes. The real Clearpath robots are created separately.
    for include in list(world.findall('include')):
        uri = include.findtext('uri', '')
        if 'fuel.' in uri or uri.endswith('/sun') or uri.endswith('/ground_plane'):
            world.remove(include)
    for plugin in list(world.findall('plugin')):
        if 'crowd' in plugin.get('name', '').lower() or 'toggle' in plugin.get('name', '').lower():
            world.remove(plugin)
    names = {p.get('name') for p in world.findall('plugin')}
    for suffix, cls in [('physics', 'Physics'), ('user-commands', 'UserCommands'),
                        ('scene-broadcaster', 'SceneBroadcaster'), ('sensors', 'Sensors'),
                        ('imu', 'Imu')]:
        name = 'ignition::gazebo::systems::'+cls
        if name not in names:
            plugin = ET.SubElement(world, 'plugin', filename=f'libignition-gazebo-{suffix}-system.so', name=name)
            if cls == 'Sensors':
                ET.SubElement(plugin, 'render_engine').text = 'ogre2'
    if world.find('light') is None:
        world.append(ET.fromstring('<light name="sun" type="directional"><pose>0 0 100 0 0 0</pose><diffuse>0.8 0.8 0.8 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.5 0.1 -0.9</direction><cast_shadows>true</cast_shadows></light>'))
    world.append(ET.fromstring('<model name="ground_plane"><static>true</static><link name="link"><collision name="collision"><geometry><plane><normal>0 0 1</normal><size>1000 1000</size></plane></geometry></collision><visual name="visual"><geometry><plane><normal>0 0 1</normal><size>1000 1000</size></plane></geometry></visual></link></model>'))
    ET.indent(tree)
    tree.write(package/'worlds/brin.sdf', encoding='unicode', xml_declaration=True)
    nav = yaml.safe_load(graph.read_text())
    for level in nav['levels'].values():
        for lane in level['lanes']:
            lane[2].pop('door_name', None)
    (package/'nav_graphs/simulation.yaml').write_text(yaml.safe_dump(nav))
    source_hashes = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                     for p in (source, package/'maps/brin_0.png',
                               simulation_models_source)}
    for asset in model_assets:
        model_sdf = package/'models'/asset/'model.sdf'
        source_hashes[f'{asset}/model.sdf'] = hashlib.sha256(
            model_sdf.read_bytes()).hexdigest()
    manifest = dict(graph=graph.name, world='brin', level='L1',
                    doors='open; door events removed only in simulation.yaml',
                    simulation_models=dict(source=simulation_models_source.name,
                                           count=len(model_names), names=model_names),
                    alignment_errors_m=errors,
                    sources=source_hashes)
    (package/'maps/generation_manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--package', type=Path, default=Path(__file__).resolve().parents[1])
    run(p.parse_args().package)
